def read_csv(name: str) -> list[dict]:
    path = DATA / name
    with path.open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def load() -> dict:
    meta = json.loads((DATA / "meta.json").read_text(encoding="utf-8"))
    d = {
        "meta": meta,
        "metrics": read_csv("model_metrics.csv"),
        "settings": read_csv("model_settings.csv"),
        "fi": read_csv("rf_feature_importance.csv"),
        "clim": read_csv("monthly_climatology.csv"),
        "sla": read_csv("sla_historical.csv"),
        "met": read_csv("meteorology.csv"),
        "pred": read_csv("model_predictions.csv"),
        "forecast": [r for r in read_csv("forecast.csv") if r.get("station")],
    }
    d["stations"] = meta["stations"]
    d["station_names"] = [s["station"] for s in d["stations"]]
    return d


def f(value, digits=4, sign=False) -> str:
    """จัดรูปตัวเลข — ค่าที่ไม่มีให้เป็น N/A ตามหลักของทั้งระบบ"""
    if value is None or value == "":
        return "N/A"
    try:
        x = float(value)
    except (TypeError, ValueError):
        return html.escape(str(value))
    s = f"{x:.{digits}f}"
    return f"+{s}" if sign and x >= 0 else s


def esc(text) -> str:
    return html.escape(str(text if text is not None else ""))


