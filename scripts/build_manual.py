def find_chrome() -> str | None:
    names = ["chrome", "google-chrome", "chromium", "msedge"]
    for n in names:
        p = shutil.which(n)
        if p:
            return p
    candidates = [
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
        r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    ]
    for c in candidates:
        if Path(c).exists():
            return c
    return None


def html_to_pdf(html_file: Path, pdf_file: Path) -> Path:
    """เรนเดอร์ HTML เป็น PDF ด้วย Chrome headless

    เขียนลงไฟล์ชั่วคราวก่อนแล้วจึงสลับทับไฟล์จริง เพราะบน Windows ถ้าไฟล์เดิม
    ถูกโปรแกรมอ่าน PDF เปิดค้างอยู่ จะเขียนทับไม่ได้ กรณีนั้นจะบันทึกเป็นชื่อใหม่
    แล้วแจ้งให้ปิดโปรแกรมที่เปิดไฟล์ ไม่เขียนทับเงียบ ๆ และไม่ทิ้งไฟล์เก่าไว้ให้เข้าใจผิด

    คืน path ของไฟล์ที่เขียนสำเร็จจริง
    """
    chrome = find_chrome()
    if not chrome:
        raise RuntimeError(
            "ไม่พบ Chrome หรือ Edge สำหรับแปลงเป็น PDF\n"
            f"เปิดไฟล์ {html_file} แล้วสั่งพิมพ์เป็น PDF เองได้")

    # profile ใหม่ทุกครั้งในโฟลเดอร์ชั่วคราวของระบบ
    # ถ้าใช้ path เดิมซ้ำ แล้วมี lock ค้างจากรอบก่อน Chrome จะออกทันทีโดยไม่เขียนไฟล์
    # และไม่แจ้งข้อผิดพลาดใด ๆ (exit code 0)
    profile = Path(tempfile.mkdtemp(prefix="sla_manual_chrome_"))
    tmp_pdf = pdf_file.with_name(pdf_file.stem + ".tmp.pdf")
    tmp_pdf.unlink(missing_ok=True)

    cmd = [
        chrome,
        "--headless=new",
        "--disable-gpu",
        "--no-sandbox",
        "--no-first-run",
        "--disable-extensions",
        f"--user-data-dir={profile}",
        "--no-pdf-header-footer",
        f"--print-to-pdf={tmp_pdf}",
        html_file.resolve().as_uri(),
    ]
    print(f"  เรนเดอร์ด้วย: {chrome}")
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
    shutil.rmtree(profile, ignore_errors=True)

    if not tmp_pdf.exists() or tmp_pdf.stat().st_size < 20_000:
        size = tmp_pdf.stat().st_size if tmp_pdf.exists() else 0
        tmp_pdf.unlink(missing_ok=True)
        raise RuntimeError(
            "Chrome ไม่ได้สร้างไฟล์ PDF ที่ใช้ได้ "
            f"(ขนาด {size:,} ไบต์ · exit code {res.returncode})\n"
            f"stdout: {res.stdout[-500:]}\n"
            f"stderr: {res.stderr[-800:]}")

    try:
        os.replace(tmp_pdf, pdf_file)
        return pdf_file
    except PermissionError:
        alt = pdf_file.with_name(pdf_file.stem + "_new.pdf")
        alt.unlink(missing_ok=True)
        os.replace(tmp_pdf, alt)
        print(f"  [เตือน] เขียนทับ {pdf_file.name} ไม่ได้ เพราะมีโปรแกรมอื่นเปิดไฟล์อยู่")
        print(f"          บันทึกเป็น {alt.name} แทน — ปิดโปรแกรมที่เปิดไฟล์เดิมแล้วรันใหม่")
        return alt


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--html-only", action="store_true",
                    help="สร้างแค่ HTML ไม่แปลงเป็น PDF")
    args = ap.parse_args()

    if not DATA.exists():
        print(f"ไม่พบโฟลเดอร์ข้อมูล {DATA}\n"
              "สร้างก่อนด้วย: python scripts/build_web_data.py", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"อ่านข้อมูลจาก : {DATA}")
    d = load()
    print(f"  {len(d['stations'])} สถานี · {len(d['metrics'])} แถว metric · "
          f"{len(d['fi'])} แถว feature importance")

    doc = build_html(d)
    HTML_PATH.write_text(doc, encoding="utf-8")
    print(f"เขียน HTML     : {HTML_PATH.name} ({len(doc.encode('utf-8')):,} ไบต์)")

    if args.html_only:
        return 0

    written_pdf = html_to_pdf(HTML_PATH, PDF_PATH)
    size = written_pdf.stat().st_size
    print(f"เขียน PDF      : {written_pdf.name} ({size:,} ไบต์)")
    print(f"\nคู่มืออยู่ที่ {written_pdf}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
