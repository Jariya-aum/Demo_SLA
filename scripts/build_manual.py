def table(head: list[str], rows: list[list[str]], caption: str = "",
          cls: str = "", first_col_text: bool = True) -> str:
    ths = "".join(
        f'<th{" class=\'text\'" if (i == 0 and first_col_text) else ""}>{h}</th>'
        for i, h in enumerate(head))
    trs = []
    for row in rows:
        tds = "".join(
            f'<td{" class=\'text\'" if (i == 0 and first_col_text) else ""}>{c}</td>'
            for i, c in enumerate(row))
        trs.append(f"<tr>{tds}</tr>")
    cap = f"<caption>{caption}</caption>" if caption else ""
    return (f'<table class="t {cls}">{cap}<thead><tr>{ths}</tr></thead>'
            f'<tbody>{"".join(trs)}</tbody></table>')


def model_chip(model: str) -> str:
    return (f'<span class="chip"><span class="sw" style="background:'
            f'{MODEL_COLOR.get(model, "#888")}"></span>{esc(MODEL_LABEL.get(model, model))}</span>')


def steps(items: list[str]) -> str:
    return '<ol class="steps">' + "".join(f"<li>{s}</li>" for s in items) + "</ol>"


def note(title: str, body: str, kind: str = "") -> str:
    return (f'<div class="note {kind}"><span class="note__t">{title}</span>'
            f'<span class="note__b">{body}</span></div>')


def kv(pairs: list[tuple[str, str]]) -> str:
    return ('<dl class="kv">'
            + "".join(f"<div><dt>{k}</dt><dd>{v}</dd></div>" for k, v in pairs)
            + "</dl>")


